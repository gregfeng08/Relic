    /// <summary>
    /// Writes readable markdown samples for review (RLC-014: "are these exciting
    /// on paper?"): docs/samples/relics-&lt;seed&gt;.md and bosses-&lt;seed&gt;.md.
    /// Pure string building; the caller writes the files.
    /// </summary>
    public static class SampleWriter
    {
        static readonly CultureInfo Ci = CultureInfo.InvariantCulture;

        public const string TemplateBanner =
            "> **TEMPLATE MODE — not LLM output.** Every name, lore paragraph and enchantment below was written by the deterministic " +
            "template generator (`TemplateAuthor`), not a language model. These samples exist so the pipeline, power budgets, stat rolls, " +
            "overrolls and boss structures can be reviewed now. LLM-written samples come after the model download is approved (RLC-026).";

        public sealed class RelicSamples
        {
            public List<Item> Relics = new List<Item>();
            public List<Item> Ordinary = new List<Item>();
            public WorldContext World;
            public ulong Seed;
            public bool TemplateMode = true;
            public string TextSource;
        }

        /// <summary>Generates the standard sample set: 50 relics (tiers cycle 0–10) plus a few ordinary drops for comparison.</summary>
        public static RelicSamples GenerateRelics(ulong seed, ITextGenerator text = null, int count = 50)
        {
            var world = StubWorld.Create(seed);
            var gen = new ItemGenerator(world, text);
            var s = new RelicSamples { World = world, Seed = seed, TemplateMode = gen.IsTemplateMode, TextSource = text?.Name ?? TemplateAuthor.Source };
            for (int i = 0; i < count; i++)
                s.Relics.Add(gen.Generate(new ItemSpec { WorldSeed = seed, Index = i, Tier = i % 11, Rarity = Rarity.Legendary }));
            Rarity[] rarities = { Rarity.Common, Rarity.Uncommon, Rarity.Rare, Rarity.Epic };
            int[] tiers = { 0, 4, 9 };
            int idx = 1000;
            foreach (var r in rarities)
                foreach (var t in tiers)
                    s.Ordinary.Add(gen.Generate(new ItemSpec { WorldSeed = seed, Index = idx++, Tier = t, Rarity = r }));
            return s;
        }

        public static List<BossDefinition> GenerateBosses(ulong seed, int count = 10)
        {
            var world = StubWorld.Create(seed);
            var list = new List<BossDefinition>();
            for (int i = 0; i < count; i++)
            {
                // Spread tiers 0..10 and make sure every archetype shows up at least once in the first eight.
                int tier = (int)Math.Round(i * 10.0 / Math.Max(1, count - 1));
                string arch = i < BossArchetypes.All.Length ? BossArchetypes.All[(i * 3) % BossArchetypes.All.Length].Id : null;
                list.Add(BossGenerator.Generate(seed, i, tier, world, arch));
            }
            return list;
        }

        // ---------- relics ----------

        public static string RelicsMarkdown(RelicSamples s)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"# Relic samples — seed {s.Seed}");
            sb.AppendLine();
            if (s.TemplateMode) { sb.AppendLine(TemplateBanner); sb.AppendLine(); }
            else { sb.AppendLine($"> LLM output from `{s.TextSource}`, validated and budget-fitted by the pipeline."); sb.AppendLine(); }
            sb.AppendLine($"Generated by `{ItemGenerator.GeneratorName}` v{ItemGenerator.GeneratorVersion} from world seed {s.Seed}: {s.Relics.Count} Legendary relics with tiers cycling 0–10, then {s.Ordinary.Count} ordinary drops for comparison. Regenerate with `RELIC_SAMPLE_SEED={s.Seed} dotnet test tools/Relic.Tests --filter Name=WriteSamples` (see Assets/Relic/Items/README.md).");
            sb.AppendLine();
            sb.AppendLine("## How to read these");
            sb.AppendLine("- **Budget** is `PowerBudget.For(rarity, tier)` in power points (pp; 1 pp ≈ one 10-damage hit every 4 s). Legendary: 25 pp at tier 0, up to 150 pp at tier 10. *Used* is what the effects cost.");
            sb.AppendLine("- **Stats** roll uniformly between the normal range's ends; an **overroll** goes past the ceiling in +5% steps (P(≥ n steps) = e^−n; hidden cap 10). `+2 (+10%)` means two steps.");
            sb.AppendLine("- **Ultimate cost** is shown twice: what the validator charges (a full resonance bar makes it cheap) and the share it takes before that relief, which the pipeline caps at 40% of the budget.");
            sb.AppendLine("- **Cursed** relics carry a drawback (negative cost) and spend the power it buys elsewhere.");
            sb.AppendLine();
            sb.AppendLine("## World context (stub, seeded)");
            sb.AppendLine(WorldMarkdown(s.World));
            sb.AppendLine();
            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.AppendLine("| # | Name | Form | Tier | Theme | Rules | Budget used | Best overroll |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            for (int i = 0; i < s.Relics.Count; i++)
            {
                var it = s.Relics[i];
                var v = EffectValidator.Validate(it.Effects, PowerBudget.For(it.Rarity, it.Tier));
                int best = it.Stats.Count == 0 ? 0 : it.Stats.Max(x => x.OverrollSteps);
                sb.AppendLine($"| {i + 1} | [{Esc(it.Name)}](#{Anchor(i + 1, it.Name)}) | {it.Form} | {it.Tier} | {it.Theme}{(IsCursed(it) ? " · cursed" : "")} | {it.Effects.Rules.Count - 1} + Q | {Pct(v.Cost / v.Budget)} | {(best > 0 ? "+" + best : "—")} |");
            }
            sb.AppendLine();
            for (int i = 0; i < s.Relics.Count; i++) sb.Append(ItemMarkdown(s.Relics[i], i + 1, s.World, true));
            sb.AppendLine("## Ordinary drops for comparison");
            sb.AppendLine();
            sb.AppendLine("Common and Uncommon items come from tables only (no text model). Rare items get a written name and one-line flavor; Epic items get lore and one written enchantment on top of the table weapon skill or passive.");
            sb.AppendLine();
            for (int i = 0; i < s.Ordinary.Count; i++) sb.Append(ItemMarkdown(s.Ordinary[i], s.Relics.Count + i + 1, s.World, false));
            return sb.ToString();
        }

        static bool IsCursed(Item it) =>
            it.Effects.Rules.Any(r => r.Actions.Any(a => PowerBudget.Cost(a) < 0f && a.Payload == null));

        public static string ItemMarkdown(Item it, int number, WorldContext world, bool full)
        {
            var sb = new StringBuilder();
            float budget = PowerBudget.For(it.Rarity, it.Tier);
            var v = EffectValidator.Validate(it.Effects, budget);
            sb.AppendLine($"## {number}. {it.Name}");
            sb.AppendLine();
            string kind = it.BaseType == BaseType.Relic ? "relic (" + it.Form + ")" : Pretty(it.BaseType.ToString());
            sb.AppendLine($"*{it.Rarity} {kind} · tier {it.Tier}{(it.Theme != null ? " · theme " + it.Theme : "")}{(IsCursed(it) ? " · **cursed**" : "")}* · `{it.Id}`");
            sb.AppendLine();
            if (it.Stats.Count > 0)
            {
                sb.AppendLine("| Stat | Value | Normal range | Overroll |");
                sb.AppendLine("|---|---|---|---|");
                foreach (var st in it.Stats)
                    sb.AppendLine($"| {StatName(st.Stat)} | **{Num(st.Value)}{Unit(st.Stat)}** | {Num(st.Min)}–{Num(st.Ceiling)} | {(st.OverrollSteps > 0 ? "+" + st.OverrollSteps + " (+" + st.OverrollSteps * 5 + "%)" : "—")} |");
                sb.AppendLine();
            }
            if (it.Lore != null)
            {
                if (it.Lore.Flavor != null) { sb.AppendLine("*\"" + it.Lore.Flavor + "\"*"); sb.AppendLine(); }
                if (it.Lore.History != null)
                {
                    sb.AppendLine("> " + it.Lore.History);
                    sb.AppendLine();
                    if (it.Lore.WorldRefs != null && it.Lore.WorldRefs.Count > 0)
                        sb.AppendLine("*Refers to:* " + string.Join(", ", it.Lore.WorldRefs.Select(id => (world?.NameOf(id) ?? id) + " (" + (world?.KindOf(id) ?? "?") + ")")));
                    sb.AppendLine();
                }
            }

            if (it.Effects.Rules.Count > 0)
            {
                sb.AppendLine("**Effects**");
                sb.AppendLine();
                int n = 1;
                foreach (var r in it.Effects.Rules)
                {
                    bool ult = it.BaseType == BaseType.Relic && r.Trigger.Kind == TriggerKind.Active;
                    string label = ult ? "Release (Q)" : it.Slot == ItemSlot.Weapon && r.Trigger.Kind == TriggerKind.Active ? "Skill (E)" : "On use";
                    string cost = Num(PowerBudget.Cost(r)) + " pp";
                    if (ult) cost += $", {Num(EffectFitter.UnrelievedCost(r))} pp before resonance relief";
                    string title = ult ? "Ultimate — " + r.Name : r.Name;
                    sb.AppendLine($"{n++}. **{Esc(title)}** — {EffectDescriber.Describe(r, label)} *({cost})*");
                }
                sb.AppendLine();
            }

            if (full && it.Visual != null)
            {
                var vis = it.Visual;
                sb.AppendLine($"**Visual** — parts: {string.Join(", ", vis.KitParts)} · material: {vis.Material} · wear {Num(vis.Wear)} · glow {vis.EmissiveColor} ×{Num(vis.EmissiveIntensity)} · decal: {vis.Decal}");
                sb.AppendLine();
            }
            var g = it.Generator;
            sb.AppendLine($"**Power** {Num(v.Cost)} / {Num(v.Budget)} pp ({Pct(v.Cost / v.Budget)}) · {(it.Effects.Rules.Count == 0 ? "no effects" : v.IsValid ? "valid" : "INVALID: " + v)}{(g.ScaleApplied < 1f ? $" · scaled ×{Num(g.ScaleApplied)} to fit" : "")} · generation: {ModeName(g.Mode)}{(g.Attempts > 0 ? ", " + g.Attempts + " attempt" + (g.Attempts > 1 ? "s" : "") : "")}");
            sb.AppendLine();
            if (full && it.Effects.Rules.Count > 0)
            {
                sb.AppendLine("<details><summary>Effect JSON (grammar format, default fields omitted)</summary>");
                sb.AppendLine();
                foreach (var r in it.Effects.Rules)
                {
                    sb.AppendLine("**" + Esc(r.Name) + "**");
                    sb.AppendLine();
                    sb.AppendLine("```json");
                    sb.AppendLine(CompactJson.Rule(r));
                    sb.AppendLine("```");
                    sb.AppendLine();
                }
                sb.AppendLine("</details>");
                sb.AppendLine();
            }
            sb.AppendLine("---");
            sb.AppendLine();
            return sb.ToString();
        }

        static string ModeName(GenerationMode m)
        {
            switch (m)
            {
                case GenerationMode.Tables: return "tables only";
                case GenerationMode.Template: return "template text";
                case GenerationMode.Llm: return "LLM text";
                default: return "LLM failed → template fallback";
            }
        }

        public static string WorldMarkdown(WorldContext w)
        {
            var sb = new StringBuilder();
            sb.AppendLine();
            sb.AppendLine("| Kind | Name | Notes |");
            sb.AppendLine("|---|---|---|");
            foreach (var r in w.Regions) sb.AppendLine($"| region (tier {r.Tier}) | {r.Name} | {string.Join(", ", r.Tags)}; landmark {r.Landmark} |");
            foreach (var f in w.Factions) sb.AppendLine($"| faction | {f.Name} | {f.Ethos}; seat {w.NameOf(f.SeatRegionId)} |");
            foreach (var p in w.Figures) sb.AppendLine($"| person | {p.Name} | {p.Title} of {w.NameOf(p.FactionId)}; {p.Fate} |");
            foreach (var e in w.Events) sb.AppendLine($"| event | {Cap(e.Name)} | {e.YearsAgo} years ago |");
            return sb.ToString();
        }

