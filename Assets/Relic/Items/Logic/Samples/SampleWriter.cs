        public static string BossesMarkdown(ulong seed, List<BossDefinition> bosses, WorldContext world)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"# Boss samples — seed {seed}");
            sb.AppendLine();
            sb.AppendLine("> **TEMPLATE MODE — not LLM output.** Boss structure (patterns, phases, numbers) is fully deterministic and always will be; the names, titles and lore here come from templates, not a language model.");
            sb.AppendLine();
            sb.AppendLine($"Generated by `{BossGenerator.GeneratorName}` v{BossGenerator.GeneratorVersion} from world seed {seed} (same stub world as `relics-{seed}.md`). Every boss below passed the readability checker.");
            sb.AppendLine();
            sb.AppendLine("## How to read these");
            sb.AppendLine("- A boss runs its current phase's **rotation** in a loop, with a recovery window after each pattern. Phases change **on health only**; there are no enrage timers.");
            sb.AppendLine("- Every damaging attack has a **physical tell** of at least 0.4 s (the wind-up). Rings and cones at tier ≤ 3 leave openings of at least 2× body width (1.2 m) at 6 m from the boss; beyond tier 3 the openings may tighten to 0.75 m. Lobbed (airborne) shots are flagged: they cast real shadows.");
            sb.AppendLine("- Later phases **remix** earlier patterns (fused, lingering, returning, shattering, doubled) instead of just speeding them up.");
            sb.AppendLine($"- **Health** = 9 DPS × (1 + 0.5 × tier) × (2 + 0.3 × tier) min × 60, times (1 + 0.8 × (players − 1)) in a group. Hit damage per projectile is 10 × (1 + 0.4 × tier) (first pass; needs player HP numbers).");
            sb.AppendLine();
            sb.AppendLine("| Tier | Solo HP | Top gear for the tier | Starter gear | 2 players | 4 players |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (int t in new[] { 0, 2, 4, 6, 8, 10 })
            {
                float hp = BossHealth.BaseHealth(t);
                sb.AppendLine($"| {t} | {hp:0} | {BossHealth.SoloMinutes(t, BossHealth.PowerBand(t)):0.0} min | {BossHealth.SoloMinutes(t, 1f):0.0} min | {BossHealth.ForPlayers(hp, 2):0} | {BossHealth.ForPlayers(hp, 4):0} |");
            }
            sb.AppendLine();
            sb.AppendLine("## Summary");
            sb.AppendLine();
            sb.AppendLine("| # | Boss | Archetype | Tier | Solo HP | Phases | Patterns | Essence |");
            sb.AppendLine("|---|---|---|---|---|---|---|---|");
            for (int i = 0; i < bosses.Count; i++)
            {
                var b = bosses[i];
                sb.AppendLine($"| {i + 1} | [{b.Name}, {b.Title}](#{Anchor(i + 1, b.Name + ", " + b.Title)}) | {b.Archetype} | {b.Tier} | {b.BaseHealth:0} | {b.Phases.Count} | {b.Phases.Sum(p => p.Patterns.Count)} | {b.Essence.Stat} +{b.Essence.Amount} |");
            }
            sb.AppendLine();
            for (int i = 0; i < bosses.Count; i++) sb.Append(BossMarkdown(bosses[i], i + 1, world));
            return sb.ToString();
        }

        public static string BossMarkdown(BossDefinition b, int number, WorldContext world)
        {
            var sb = new StringBuilder();
            var rep = ReadabilityChecker.Check(b);
            sb.AppendLine($"## {number}. {b.Name}, {b.Title}");
            sb.AppendLine();
            sb.AppendLine($"*{b.Archetype} · tier {b.Tier} · {b.BaseHealth:0} HP solo ({BossHealth.ForPlayers(b.BaseHealth, 2):0} for two, {BossHealth.ForPlayers(b.BaseHealth, 4):0} for four) · drops **{b.Essence.Name}** ({b.Essence.Stat} +{b.Essence.Amount})* · `{b.Id}`");
            sb.AppendLine();
            sb.AppendLine("> " + b.Lore);
            sb.AppendLine();
            if (b.WorldRefs.Count > 0) sb.AppendLine("*Refers to:* " + string.Join(", ", b.WorldRefs.Select(id => (world?.NameOf(id) ?? id) + " (" + (world?.KindOf(id) ?? "?") + ")")));
            sb.AppendLine();
            sb.AppendLine($"**Arena:** {Cap(b.Arena)}. **Hazards:** {string.Join("; ", b.Hazards)}.");
            sb.AppendLine();
            sb.AppendLine($"Fight length solo: about {BossHealth.SoloMinutes(b.Tier, BossHealth.PowerBand(b.Tier)):0.#} min with top gear for the tier, {BossHealth.SoloMinutes(b.Tier, 1f):0.#} min with starter gear.");
            sb.AppendLine();
            foreach (var ph in b.Phases)
            {
                sb.AppendLine($"### Phase {ph.Index} — {(ph.Index == 1 ? "from full health" : "below " + Pct(ph.StartsAtHealth) + " health")}");
                sb.AppendLine();
                if (ph.Index > 1) { sb.AppendLine("*Changes:* " + ph.Change + "."); sb.AppendLine(); }
                sb.AppendLine("Rotation: " + string.Join(" → ", ph.Rotation.Select(r => ph.Patterns[r.Pattern].Name)) + $" (then repeats; {Num(ph.Rotation[0].Recover)} s recovery after each)");
                sb.AppendLine();
                foreach (var p in ph.Patterns)
                {
                    string tag = p.Remix != null ? $" *(remix — {p.Remix} {p.RemixOf})*" : "";
                    sb.AppendLine($"- **{Esc(p.Name)}**{tag} · {string.Join(" + ", p.Blocks)} · wind-up {Num(p.WindUp)} s · lasts {Num(p.Duration)} s{(p.Airborne ? " · **airborne** (watch the shadows)" : "")}");
                    sb.AppendLine($"  - *Tell:* {p.Tell}");
                    foreach (var r in p.Program.Rules)
                        sb.AppendLine($"  - *Does:* {EffectDescriber.Describe(r, "Attack", boss: true)}");
                }
                sb.AppendLine();
            }
            string gap = rep.SmallestGap < float.MaxValue ? $"smallest opening {Num(rep.SmallestGap)} m at {Num(Readability.ReferenceDistance)} m" : "no rings or cones";
            sb.AppendLine($"**Readability:** {(rep.Passed ? "passed" : "FAILED — " + rep)} · {gap} · shortest wind-up {Num(rep.ShortestWindUp)} s · airborne patterns: {(rep.AirborneFlags.Count > 0 ? string.Join(", ", rep.AirborneFlags.Distinct()) : "none")}");
            sb.AppendLine();
            sb.AppendLine("<details><summary>Pattern JSON (grammar format, default fields omitted)</summary>");
            sb.AppendLine();
            var shown = new HashSet<string>();
            foreach (var ph in b.Phases)
                foreach (var p in ph.Patterns)
                {
                    if (!shown.Add(p.Name)) continue;
                    sb.AppendLine("**" + Esc(p.Name) + "**");
                    sb.AppendLine();
                    sb.AppendLine("```json");
                    sb.AppendLine(CompactJson.Program(p.Program));
                    sb.AppendLine("```");
                    sb.AppendLine();
                }
            sb.AppendLine("</details>");
            sb.AppendLine();
            sb.AppendLine("---");
            sb.AppendLine();
            return sb.ToString();
        }

        // ---------- formatting ----------

        static string Num(float v) => v.ToString("0.##", Ci);
        static string Pct(float v) => (v * 100f).ToString("0", Ci) + "%";
        static string Cap(string s) => string.IsNullOrEmpty(s) ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);
        static string Esc(string s) => s?.Replace("|", "\\|");

        static string Pretty(string camel)
        {
            var sb = new StringBuilder();
            for (int i = 0; i < camel.Length; i++)
            {
                if (i > 0 && char.IsUpper(camel[i])) sb.Append(' ').Append(char.ToLowerInvariant(camel[i]));
                else sb.Append(i == 0 ? camel[i] : camel[i]);
            }
            return sb.ToString();
        }

        /// <summary>GitHub-style heading anchor for "## {n}. {title}".</summary>
        static string Anchor(int n, string title)
        {
            var sb = new StringBuilder();
            foreach (char c in (n + ". " + title).ToLowerInvariant())
            {
                if (char.IsLetterOrDigit(c) || c == '-' || c == '_') sb.Append(c);
                else if (c == ' ') sb.Append('-');
            }
            return sb.ToString();
        }

        static string StatName(ItemStatKind k)
        {
            switch (k)
            {
                case ItemStatKind.Damage: return "Damage per hit";
                case ItemStatKind.AttackSpeed: return "Attacks per second";
                case ItemStatKind.CritChance: return "Crit chance";
                case ItemStatKind.SkillPower: return "Skill power";
                case ItemStatKind.Defense: return "Defense (DEF)";
                case ItemStatKind.MaxHealth: return "Max HP";
                case ItemStatKind.MaxMana: return "Max mana";
                case ItemStatKind.MaxStamina: return "Max stamina";
                case ItemStatKind.MoveSpeed: return "Move speed";
                case ItemStatKind.ManaRegen: return "Mana regen /s";
                case ItemStatKind.StatusResist: return "Status resistance";
                case ItemStatKind.ResonanceGain: return "Resonance gain";
                case ItemStatKind.Strength: return "STR";
                case ItemStatKind.Agility: return "AGI";
                case ItemStatKind.Vitality: return "VIT";
                case ItemStatKind.Intelligence: return "INT";
                case ItemStatKind.Insight: return "INS";
                case ItemStatKind.Charisma: return "CHR";
            }
            return k.ToString();
        }

        static string Unit(ItemStatKind k) => StatTables.IsPercent(k) ? "%" : "";
    }
