using System;
using System.Collections.Generic;
using System.IO;

namespace Relic.Lore
{
    /// <summary>
    /// The Lore Bible in memory. Loaded from data it is the <b>constitution</b>: style rules,
    /// moods, motifs, faction and event templates, culture templates, phonology families,
    /// item-form tags and prehistory templates, with no cultures, eras or legends of its own.
    /// <see cref="ForWorld"/> instantiates it for one world seed: the returned bible shares
    /// the rules and adds that world's generated <see cref="Cultures"/>, <see cref="Eras"/>,
    /// <see cref="Legends"/> (founders, figures, artifacts) and <see cref="History"/>.
    /// Load it with <see cref="LoadDirectory"/> (tools, tests) or <see cref="FromJson"/>
    /// (Unity TextAssets). Both validate and throw <see cref="LoreDataException"/>.
    /// </summary>
    public sealed class LoreBible
    {
        public const string PhonologyFile = "phonology.json";
        public const string FormsFile = "forms.json";
        public const string CultureTemplatesFile = "culture-templates.json";
        public const string PrehistoryFile = "prehistory.json";
        public const string FactionsFile = "factions.json";
        public const string EventsFile = "events.json";
        public const string MotifsFile = "motifs.json";
        public const string MoodsFile = "moods.json";
        public const string StyleFile = "style.json";

        /// <summary>Every data file, in the order <see cref="FromJson"/> takes them.</summary>
        public static readonly string[] Files =
        {
            PhonologyFile, FormsFile, CultureTemplatesFile, PrehistoryFile, FactionsFile, EventsFile, MotifsFile, MoodsFile, StyleFile,
        };

        // ---- rules (shared by every world) ----
        public List<PhonologyFamily> Phonologies = new List<PhonologyFamily>();
        public List<FormTag> Forms = new List<FormTag>();
        public List<CultureTemplate> CultureTemplates = new List<CultureTemplate>();
        public PrehistoryRules PrehistoryRules = new PrehistoryRules();
        public List<FactionArchetype> Factions = new List<FactionArchetype>();
        public List<EventTemplate> Events = new List<EventTemplate>();
        public List<MotifDef> Motifs = new List<MotifDef>();
        public MoodTable Moods = new MoodTable();
        public StyleRules Style = new StyleRules();

        // ---- world (generated by ForWorld; empty in the constitution) ----
        /// <summary>The world seed this bible was instantiated for, or null for the constitution.</summary>
        public ulong? WorldSeed;
        public List<CultureDef> Cultures = new List<CultureDef>();
        public List<EraDef> Eras = new List<EraDef>();
        /// <summary>Founders, figures and artifacts from the world's prehistory.</summary>
        public List<LegendDef> Legends = new List<LegendDef>();
        public WorldPrehistory History;

        /// <summary>True when this is a world instance (cultures and prehistory generated).</summary>
        public bool IsWorld => WorldSeed.HasValue;

        public CultureDef Culture(string id) => Cultures.Find(c => c.Id == id);
        public FactionArchetype Faction(string id) => Factions.Find(f => f.Id == id);
        public EventTemplate Event(string id) => Events.Find(e => e.Id == id);
        public MotifDef Motif(string id) => Motifs.Find(m => m.Id == id);
        public MoodDef Mood(string id) => Moods.Moods.Find(m => m.Id == id);
        public EraDef Era(string id) => Eras.Find(e => e.Id == id);
        public LegendDef Legend(string id) => Legends.Find(l => l.Id == id);
        public PhonologyFamily Phonology(string id) => Phonologies.Find(p => p.Id == id);
        public CultureTemplate CultureTemplate(string id) => CultureTemplates.Find(t => t.Id == id);
        public EraTemplate EraTemplate(string id) => PrehistoryRules.Eras.Find(t => t.Id == id);

        /// <summary>Tags for one form name (a form may have two: trinket and relic).</summary>
        public List<FormTag> FormTagsOf(string form) =>
            Forms.FindAll(f => string.Equals(f.Form, form, StringComparison.OrdinalIgnoreCase));

        /// <summary>Cultures that list this family, in data order (strongest claim first).</summary>
        public List<CultureDef> CulturesOf(LoreFamily family)
        {
            var primary = new List<CultureDef>();
            var secondary = new List<CultureDef>();
            foreach (var c in Cultures)
            {
                int i = c.Families.IndexOf(family);
                if (i == 0) primary.Add(c);
                else if (i > 0) secondary.Add(c);
            }
            primary.AddRange(secondary);
            return primary;
        }

        /// <summary>
        /// This world's bible: the same rules plus cultures (5–8, <see cref="CultureGenerator"/>)
        /// and a prehistory (<see cref="WorldPrehistory"/>), all deterministic from the seed.
        /// The constitution itself is never modified.
        /// </summary>
        public LoreBible ForWorld(ulong worldSeed)
        {
            var w = new LoreBible
            {
                Phonologies = Phonologies, Forms = Forms, CultureTemplates = CultureTemplates, PrehistoryRules = PrehistoryRules,
                Factions = Factions, Events = Events, Motifs = Motifs, Moods = Moods, Style = Style,
                WorldSeed = worldSeed,
            };
            w.Cultures = CultureGenerator.Generate(this, worldSeed);
            w.History = WorldPrehistory.Generate(w, worldSeed);
            w.Eras = w.History.Eras;
            w.Legends = w.History.Legends;
            var errors = LoreValidator.Validate(w);
            if (errors.Count > 0)
                throw new LoreDataException("World " + worldSeed + " lore has " + errors.Count + " problem(s):\n  " + string.Join("\n  ", errors));
            return w;
        }

        /// <summary>Builds the constitution from raw JSON texts, keyed by file name (<see cref="Files"/>).</summary>
        public static LoreBible FromJson(IDictionary<string, string> docs)
        {
            string Doc(string f)
            {
                if (docs == null || !docs.TryGetValue(f, out var text)) throw new LoreDataException("Missing lore document: " + f);
                return text;
            }
            var bible = new LoreBible
            {
                Phonologies = LoreJson.Parse<List<PhonologyFamily>>(Doc(PhonologyFile), PhonologyFile),
                Forms = LoreJson.Parse<List<FormTag>>(Doc(FormsFile), FormsFile),
                CultureTemplates = LoreJson.Parse<List<CultureTemplate>>(Doc(CultureTemplatesFile), CultureTemplatesFile),
                PrehistoryRules = LoreJson.Parse<PrehistoryRules>(Doc(PrehistoryFile), PrehistoryFile),
                Factions = LoreJson.Parse<List<FactionArchetype>>(Doc(FactionsFile), FactionsFile),
                Events = LoreJson.Parse<List<EventTemplate>>(Doc(EventsFile), EventsFile),
                Motifs = LoreJson.Parse<List<MotifDef>>(Doc(MotifsFile), MotifsFile),
                Moods = LoreJson.Parse<MoodTable>(Doc(MoodsFile), MoodsFile),
                Style = LoreJson.Parse<StyleRules>(Doc(StyleFile), StyleFile),
            };
            var errors = LoreValidator.Validate(bible);
            if (errors.Count > 0)
                throw new LoreDataException("Lore Bible has " + errors.Count + " problem(s):\n  " + string.Join("\n  ", errors));
            return bible;
        }

        /// <summary>Loads Assets/Relic/Lore/Data (or any folder with the same files).</summary>
        public static LoreBible LoadDirectory(string dataDir)
        {
            if (!Directory.Exists(dataDir)) throw new LoreDataException("Lore data folder not found: " + dataDir);
            var docs = new Dictionary<string, string>();
            foreach (var f in Files)
            {
                string path = Path.Combine(dataDir, f);
                if (!File.Exists(path)) throw new LoreDataException("Missing lore file: " + path);
                docs[f] = File.ReadAllText(path);
            }
            return FromJson(docs);
        }
    }
}
